"""组合/组件 Alpha 衰减月度监控 — AlphaDecayMonitor。

提供策略/组合级别的 alpha 衰减检测与月度报告生成：
- 滚动 SR（12M / 6M / 3M）趋势追踪
- DR-AR-004 预警: 近 3 年滚动 SR < 全量 SR × 40%
- PSI 信号漂移检测（收益率分布稳定性）
- 月度 Markdown 报告自动生成
- 飞书/告警分级集成

理论基础:
- McLean & Pontiff (2016): alpha 衰减与出版后效应
- DR-AR-004 (decision_rule_registry): 近3年SR衰减预警
- PSI > 0.20 → 显著分布漂移(知识库 ML T3)

Usage::

    monitor = AlphaDecayMonitor.from_nav_csv("output/v6d_final_replay/daily_nav.csv")
    report = monitor.generate_monthly_report()
    print(report.to_markdown())
    if report.alert_level == "CRITICAL":
        monitor.send_alert(report)
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Optional

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

# 年化交易日(§13.8: 中国 A 股标准值)
TRADING_DAYS_PER_YEAR = 244


class AlertLevel(Enum):
    """告警级别。"""
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


@dataclass
class RollingSRSnapshot:
    """滚动 SR 快照。"""
    window_months: int
    sr_value: float
    start_date: str
    end_date: str


@dataclass
class DecayReport:
    """月度衰减报告。"""
    profile_name: str
    report_date: str
    full_period_sr: float
    rolling_sr_12m: float
    rolling_sr_6m: float
    rolling_sr_3m: float
    dr_ar004_ratio: float  # rolling_3y_sr / full_sr
    dr_ar004_triggered: bool  # ratio < 0.40
    psi_value: float
    psi_status: str  # "stable" / "warning" / "drifted"
    alert_level: AlertLevel = AlertLevel.INFO
    yearly_sr_trend: dict[str, float] = field(default_factory=dict)
    details: dict[str, Any] = field(default_factory=dict)

    def to_markdown(self) -> str:
        """生成 Markdown 格式报告。"""
        alert_icon = {"INFO": "🟢", "WARNING": "⚠️", "CRITICAL": "🔴"}
        icon = alert_icon.get(self.alert_level.value, "")

        lines = [
            f"# Alpha 衰减月度报告 — {self.profile_name}",
            f"",
            f"**报告日期**: {self.report_date}  ",
            f"**告警级别**: {icon} {self.alert_level.value}",
            f"",
            f"## 1. 滚动 Sharpe Ratio",
            f"",
            f"| 窗口 | SR | vs 全量期 |",
            f"|------|-----|-----------|",
            f"| 全量期 | {self.full_period_sr:.3f} | — |",
            f"| 12M | {self.rolling_sr_12m:.3f} | {self._ratio_str(self.rolling_sr_12m)} |",
            f"| 6M | {self.rolling_sr_6m:.3f} | {self._ratio_str(self.rolling_sr_6m)} |",
            f"| 3M | {self.rolling_sr_3m:.3f} | {self._ratio_str(self.rolling_sr_3m)} |",
            f"",
            f"## 2. DR-AR-004 衰减检验",
            f"",
            f"- 近3年SR / 全量SR = **{self.dr_ar004_ratio:.1%}** (阈值: 40%)",
            f"- 状态: {'🔴 **触发降权预警**' if self.dr_ar004_triggered else '✅ 正常'}",
            f"",
            f"## 3. PSI 分布漂移",
            f"",
            f"- PSI = **{self.psi_value:.4f}**",
            f"- 判定: {self.psi_status} ({'< 0.10 稳定' if self.psi_status == 'stable' else '0.10-0.20 关注' if self.psi_status == 'warning' else '≥ 0.20 显著漂移'})",
            f"",
            f"## 4. 逐年 SR 趋势",
            f"",
            f"| 年份 | SR |",
            f"|------|-----|",
        ]
        for year, sr in sorted(self.yearly_sr_trend.items()):
            lines.append(f"| {year} | {sr:.3f} |")

        lines.append("")
        lines.append("---")
        lines.append(f"*Generated by AlphaDecayMonitor*")
        return "\n".join(lines)

    def _ratio_str(self, sr_val: float) -> str:
        """生成 vs 全量期的比值字符串。"""
        if self.full_period_sr <= 0:
            return "N/A"
        ratio = sr_val / self.full_period_sr
        return f"{ratio:.0%}"

    def to_dict(self) -> dict[str, Any]:
        """序列化为字典。"""
        return {
            "profile_name": self.profile_name,
            "report_date": self.report_date,
            "full_period_sr": self.full_period_sr,
            "rolling_sr_12m": self.rolling_sr_12m,
            "rolling_sr_6m": self.rolling_sr_6m,
            "rolling_sr_3m": self.rolling_sr_3m,
            "dr_ar004_ratio": self.dr_ar004_ratio,
            "dr_ar004_triggered": self.dr_ar004_triggered,
            "psi_value": self.psi_value,
            "psi_status": self.psi_status,
            "alert_level": self.alert_level.value,
            "yearly_sr_trend": self.yearly_sr_trend,
        }


class AlphaDecayMonitor:
    """组合/组件 Alpha 衰减月度监控器。"""

    def __init__(
        self,
        nav_series: pd.Series,
        profile_name: str = "unnamed",
        full_sr_override: Optional[float] = None,
    ) -> None:
        """初始化。

        Args:
            nav_series: 日频 NAV 序列 (DatetimeIndex)
            profile_name: 组合/组件名称
            full_sr_override: 可选全量 SR 覆盖值 (用于外部基线)
        """
        self._nav = nav_series.sort_index().copy()
        self._returns = self._nav.pct_change().dropna()
        self._profile_name = profile_name
        self._full_sr_override = full_sr_override

    @classmethod
    def from_nav_csv(
        cls,
        csv_path: str | Path,
        profile_name: Optional[str] = None,
        nav_col: str = "nav",
        date_col: str = "date",
    ) -> AlphaDecayMonitor:
        """从 NAV CSV 文件加载。"""
        path = Path(csv_path)
        df = pd.read_csv(path)
        df[date_col] = pd.to_datetime(df[date_col])
        df = df.set_index(date_col).sort_index()
        nav_series = df[nav_col].astype(float)
        name = profile_name or path.parent.name
        return cls(nav_series, profile_name=name)

    def compute_rolling_sr(self, window_days: int) -> pd.Series:
        """计算滚动年化 Sharpe Ratio。

        Args:
            window_days: 滚动窗口交易日数

        Returns:
            滚动 SR 时间序列 (DatetimeIndex)
        """
        if len(self._returns) < window_days:
            return pd.Series(dtype=float)
        ann_factor = np.sqrt(TRADING_DAYS_PER_YEAR)
        rolling_mean = self._returns.rolling(window_days).mean()
        rolling_std = self._returns.rolling(window_days).std()
        sr = (rolling_mean / rolling_std.where(rolling_std > 1e-12)) * ann_factor
        return sr.dropna()

    def compute_full_period_sr(self) -> float:
        """计算全量期年化 SR。"""
        if self._full_sr_override is not None:
            return self._full_sr_override
        if len(self._returns) < 60:
            return 0.0
        ann_factor = np.sqrt(TRADING_DAYS_PER_YEAR)
        mean_ret = self._returns.mean()
        std_ret = self._returns.std()
        if std_ret < 1e-12:
            return 0.0
        return float(mean_ret / std_ret * ann_factor)

    def check_dr_ar004(self, recent_years: int = 3) -> tuple[float, bool]:
        """DR-AR-004 检查: 近N年SR / 全量SR < 40% → 触发降权预警。

        Returns:
            (ratio, triggered): ratio = recent_sr / full_sr; triggered = ratio < 0.40
        """
        full_sr = self.compute_full_period_sr()
        if full_sr <= 0:
            return 0.0, False

        recent_days = recent_years * TRADING_DAYS_PER_YEAR
        if len(self._returns) < recent_days:
            # 数据不足，使用全部数据
            recent_rets = self._returns
        else:
            recent_rets = self._returns.iloc[-recent_days:]

        ann_factor = np.sqrt(TRADING_DAYS_PER_YEAR)
        recent_mean = recent_rets.mean()
        recent_std = recent_rets.std()
        if recent_std < 1e-12:
            return 0.0, True
        recent_sr = float(recent_mean / recent_std * ann_factor)

        ratio = recent_sr / full_sr
        triggered = ratio < 0.40
        return ratio, triggered

    def compute_psi(self, baseline_days: int = 504, recent_days: int = 63) -> tuple[float, str]:
        """计算收益率分布 PSI (Population Stability Index)。

        Args:
            baseline_days: 基线窗口大小 (默认约2年)
            recent_days: 近期窗口大小 (默认约3月)

        Returns:
            (psi_value, status): PSI 值及判定 ("stable"/"warning"/"drifted")
        """
        n = len(self._returns)
        if n < baseline_days + recent_days:
            return 0.0, "stable"

        baseline = self._returns.iloc[-(baseline_days + recent_days):-recent_days].values
        recent = self._returns.iloc[-recent_days:].values

        # 使用 10 分位 bins
        n_bins = 10
        edges = np.percentile(baseline, np.linspace(0, 100, n_bins + 1))
        edges[0] = -np.inf
        edges[-1] = np.inf

        base_counts = np.histogram(baseline, bins=edges)[0].astype(float)
        curr_counts = np.histogram(recent, bins=edges)[0].astype(float)

        # 避免零除 (Laplace smoothing)
        base_pct = (base_counts + 0.5) / (base_counts.sum() + n_bins * 0.5)
        curr_pct = (curr_counts + 0.5) / (curr_counts.sum() + n_bins * 0.5)

        psi = float(np.sum((curr_pct - base_pct) * np.log(curr_pct / base_pct)))

        if psi >= 0.20:
            status = "drifted"
        elif psi >= 0.10:
            status = "warning"
        else:
            status = "stable"

        return psi, status

    def compute_yearly_sr(self) -> dict[str, float]:
        """计算逐年 SR (每个自然年独立计算)。"""
        if len(self._returns) == 0:
            return {}
        ann_factor = np.sqrt(TRADING_DAYS_PER_YEAR)
        yearly = {}
        for year, grp in self._returns.groupby(self._returns.index.year):
            if len(grp) < 20:
                continue
            mean_r = grp.mean()
            std_r = grp.std()
            sr = float(mean_r / std_r * ann_factor) if std_r > 1e-12 else 0.0
            yearly[str(year)] = round(sr, 3)
        return yearly

    def generate_monthly_report(self) -> DecayReport:
        """生成月度衰减报告。"""
        from datetime import datetime

        report_date = datetime.now().strftime("%Y-%m-%d")

        # 核心指标计算
        full_sr = self.compute_full_period_sr()

        # 滚动 SR (取最新值)
        sr_12m = self._latest_rolling_sr(TRADING_DAYS_PER_YEAR)
        sr_6m = self._latest_rolling_sr(TRADING_DAYS_PER_YEAR // 2)
        sr_3m = self._latest_rolling_sr(TRADING_DAYS_PER_YEAR // 4)

        # DR-AR-004
        ar004_ratio, ar004_triggered = self.check_dr_ar004(recent_years=3)

        # PSI
        psi_val, psi_status = self.compute_psi()

        # Yearly SR trend
        yearly_sr = self.compute_yearly_sr()

        report = DecayReport(
            profile_name=self._profile_name,
            report_date=report_date,
            full_period_sr=round(full_sr, 3),
            rolling_sr_12m=round(sr_12m, 3),
            rolling_sr_6m=round(sr_6m, 3),
            rolling_sr_3m=round(sr_3m, 3),
            dr_ar004_ratio=round(ar004_ratio, 3),
            dr_ar004_triggered=ar004_triggered,
            psi_value=round(psi_val, 4),
            psi_status=psi_status,
            yearly_sr_trend=yearly_sr,
        )

        # 确定告警级别
        report.alert_level = self.determine_alert_level(report)
        return report

    def _latest_rolling_sr(self, window_days: int) -> float:
        """获取滚动 SR 最新值。"""
        sr_series = self.compute_rolling_sr(window_days)
        if len(sr_series) == 0:
            return 0.0
        return float(sr_series.iloc[-1])

    def determine_alert_level(self, report: DecayReport) -> AlertLevel:
        """根据报告指标确定告警级别。

        CRITICAL: DR-AR-004 触发 或 PSI drifted 或 12M SR < 0
        WARNING: PSI warning 或 12M SR < full_sr * 60% 或 3M SR < 0
        INFO: 其他
        """
        if report.dr_ar004_triggered:
            return AlertLevel.CRITICAL
        if report.psi_status == "drifted":
            return AlertLevel.CRITICAL
        if report.rolling_sr_12m < 0:
            return AlertLevel.CRITICAL

        if report.psi_status == "warning":
            return AlertLevel.WARNING
        if report.full_period_sr > 0 and report.rolling_sr_12m < report.full_period_sr * 0.6:
            return AlertLevel.WARNING
        if report.rolling_sr_3m < 0:
            return AlertLevel.WARNING

        return AlertLevel.INFO
