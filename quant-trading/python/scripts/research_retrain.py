#!/usr/bin/env python
"""Canonical retraining entry point for the low-frequency A-share pipeline.

This command intentionally accepts a frozen, attested Parquet snapshot only.
It does not call ``train_ml_factor.py``, scan legacy caches, or fall back to a
different market-data provider.  TuShare snapshot materialization is exposed
through the ``ml_ranking`` bridge's ``train_tushare`` action; this command is
the local/offline equivalent used by scheduled jobs and reproducible runs.

Examples::

    python scripts/research_retrain.py \
        --data-path data/snapshots/csi500.parquet \
        --output-dir output/research/runs

The input must have a sibling ``.metadata.json`` sidecar generated by the
canonical snapshot builder.  The resulting run folder contains the model,
OOS predictions, portfolio replay, report, and target execution plans.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run canonical TuShare-PIT A-share ML retraining from a frozen snapshot",
    )
    parser.add_argument("--data-path", required=True, help="attested feature snapshot Parquet")
    parser.add_argument(
        "--output-dir",
        default="output/research/runs",
        help="directory for immutable research run artifacts",
    )
    parser.add_argument(
        "--config",
        default=None,
        help="canonical research YAML (defaults to aipha/configs/research/a_stock_ml.yaml)",
    )
    parser.add_argument(
        "--data-snapshot-id",
        default=None,
        help="optional snapshot id; when supplied it must match the sidecar",
    )
    return parser.parse_args(argv)


def run(argv: list[str] | None = None) -> dict:
    args = parse_args(argv)
    project_root = Path(__file__).resolve().parents[1]
    if str(project_root) not in sys.path:
        sys.path.insert(0, str(project_root))

    from aipha.engines.aipha_ml_engine import run as canonical_run

    response = canonical_run({
        "action": "train",
        "dataPath": str(Path(args.data_path).expanduser()),
        "outputDir": str(Path(args.output_dir).expanduser()),
        "configPath": args.config,
        "dataSnapshotId": args.data_snapshot_id,
    })
    if not response.get("ok"):
        raise RuntimeError(response.get("error") or "canonical research retraining failed")
    return response["data"]


def main(argv: list[str] | None = None) -> int:
    try:
        result = run(argv)
    except Exception as exc:  # pragma: no cover - CLI presentation
        print(f"canonical retraining failed: {exc}", file=sys.stderr)
        return 1
    artifact_dir = result.get("artifact_dir", result.get("run_dir"))
    plan_paths = result.get("execution_plan_paths", [])
    if not plan_paths and artifact_dir:
        plan_paths = [str(Path(artifact_dir) / path) for path in result.get("execution_plans", [])]
    print(json.dumps({
        "ok": True,
        "runId": result.get("runId"),
        "runDir": artifact_dir,
        "reportPath": result.get("report_path") or (str(Path(artifact_dir) / "report.json") if artifact_dir else None),
        "executionPlanPaths": plan_paths,
    }, ensure_ascii=False, indent=2, default=str))
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI presentation
    raise SystemExit(main())
