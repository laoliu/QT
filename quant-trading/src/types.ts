export type ActiveLiveStrategy = {
  id: string; // e.g. "ls-001"
  strategyId: string; // references StrategyDefinition.id
  symbols: string[];
  parameters?: Record<string, unknown>;
  /** K-line interval — default "1d" (daily). Use "5m"/"15m" for intraday. */
  interval?: KlineInterval;
  enabled: boolean;
  maxPositionPct?: number; // max % of total assets per position
  maxOrderValue?: number; // override global limit for this strategy
  addedAt: string;
  /**
   * Optional time windows restricting when the strategy generates signals.
   * Each entry is an "HH:MM-HH:MM" string in market local time (e.g. "09:45-10:30").
   * If set, the strategy only runs during these windows. Empty/undefined = all market hours.
   */
  timeWindows?: string[];
  /**
   * Number of consecutive bars that a signal must persist before it is confirmed.
   * For example, confirmationBars=3 means a breakout buy signal must appear
   * in 3 consecutive check cycles before it is actually emitted. Default: 0 (no confirmation).
   */
  confirmationBars?: number;
  /**
   * Market regimes where this strategy is active. If set, the strategy is
   * auto-paused when the detected regime doesn't match any of these values.
   * Values from strategy_router: "bull", "bear", "sideways", "volatile".
   * Empty/undefined = active in all regimes.
   */
  regimes?: string[];
  /**
   * Whether this strategy is auto-paused by regime mismatch.
   * Different from `enabled` which is user-controlled. `regimePaused`
   * is system-controlled and auto-restored when regime matches again.
   */
  regimePaused?: boolean;
};

