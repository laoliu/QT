/**
 * ScanHistoryStore — persistent store for stock screening results.
 *
 * Every time a user runs a screening (via stock_screen tool),
 * the results are auto-saved here. This enables:
 *   - Reviewing past screening results by date/screener
 *   - Comparing how the same stock's score/ranking changed over time
 *   - Tracking which stocks appear repeatedly across scans
 *   - Building a "recommendation frequency" heatmap
 *
 * Architecture mirrors BacktestStore: in-memory index + per-run JSON files.
 */
import { randomUUID } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { AsyncMutex } from "../utils/async-mutex.js";

// ── Types ────────────────────────────────────────────────────────

/** A single stock entry within a scan result */
export type ScanStockEntry = {
  /** Stock code (e.g. "600519") */
  code: string;
  /** Stock name (e.g. "贵州茅台") */
  name?: string;
  /** Score from the screener (e.g. F-Score 0-9) */
  score?: number;
  /** Rank within this scan */
  rank?: number;
  /** Screener-specific factors / metrics */
  factors?: Record<string, unknown>;
  /** Signals/reasons generated by the screener */
  signals?: string[];
};

/** Full record of a single screening run */
export type ScanRecord = {
  /** Unique scan id */
  id: string;
  /** When this scan was executed (ISO-8601) */
  createdAt: string;
  /** Date portion "YYYY-MM-DD" for easy daily grouping */
  date: string;
  /** Screener used (e.g. "fscore", "canslim", "technical") */
  screenerId: string;
  /** Universe / stock pool scanned (e.g. "hs300", "zz500", "all") */
  universe: string;
  /** Market (e.g. "cn_stock") */
  market: string;
  /** Total stocks screened before filtering */
  totalScreened: number;
  /** Number of stocks that passed the screen */
  resultCount: number;
  /** The filtered/ranked stock list */
  results: ScanStockEntry[];
  /** Optional user tags */
  tags: string[];
  /** Optional notes */
  notes?: string;
};

/** Lightweight index entry (no per-stock factors) */
export type ScanIndexEntry = {
  id: string;
  createdAt: string;
  date: string;
  screenerId: string;
  universe: string;
  market: string;
  totalScreened: number;
  resultCount: number;
  /** Top stock codes (first 10) for quick preview */
  topCodes: string[];
  tags: string[];
  notes?: string;
};

export type ScanQuery = {
  /** Filter by screener id */
  screenerId?: string;
  /** Filter by universe */
  universe?: string;
  /** Filter by market */
  market?: string;
  /** Filter by date "YYYY-MM-DD" */
  date?: string;
  /** Filter by tag */
  tag?: string;
  /** Results created after this ISO timestamp */
  after?: string;
  /** Results created before this ISO timestamp */
  before?: string;
  /** Sort field */
  sortBy?: "createdAt" | "resultCount";
  /** Sort direction */
  sortDir?: "asc" | "desc";
  /** Max results (default: 50) */
  limit?: number;
  /** Pagination offset */
  offset?: number;
};

/** Tracks a stock's appearance across scans */
export type StockFrequency = {
  code: string;
  name?: string;
  /** Number of scans this stock appeared in */
  appearances: number;
  /** Dates it appeared */
  dates: string[];
  /** Average score across appearances (if scored) */
  avgScore?: number;
  /** Latest score */
  latestScore?: number;
};

/** Comparison of two scan runs */
export type ScanComparison = {
  baseId: string;
  compareId: string;
  baseDate: string;
  compareDate: string;
  screenerId: string;
  /** Stocks that appear in both scans */
  overlap: Array<{
    code: string;
    name?: string;
    baseScore?: number;
    compareScore?: number;
    scoreDelta?: number;
  }>;
  /** Stocks only in the base (earlier) scan — dropped out */
  removed: ScanStockEntry[];
  /** Stocks only in the compare (later) scan — newly appeared */
  added: ScanStockEntry[];
  overlapCount: number;
  removedCount: number;
  addedCount: number;
};

// ── Config ───────────────────────────────────────────────────────

export type ScanHistoryStoreConfig = {
  /** Directory for storing scan files (undefined disables persistence) */
  dataDir?: string;
  /** Maximum number of scans to keep (default: 200) */
  maxResults?: number;
};

const DEFAULT_MAX_RESULTS = 200;

// ── Store implementation ─────────────────────────────────────────

function generateScanId(): string {
  return `scan_${Date.now()}_${randomUUID().slice(0, 8)}`;
}

export class ScanHistoryStore {
  private readonly dataDir: string | undefined;
  private readonly maxResults: number;
  private index: ScanIndexEntry[] = [];
  private readonly writeMutex = new AsyncMutex();

  constructor(config: ScanHistoryStoreConfig) {
    this.dataDir = config.dataDir;
    this.maxResults = config.maxResults ?? DEFAULT_MAX_RESULTS;
  }

  // ── Lifecycle ─────────────────────────────────────────────────

  /** Load index from disk. Call once at startup. */
  start(): void {
    this.ensureDir();
    this.loadIndex();
  }

  get size(): number {
    return this.index.length;
  }

  // ── Write operations ──────────────────────────────────────────

  /** Save a screening result. Returns the generated scan id. */
  async save(
    screenerId: string,
    universe: string,
    market: string,
    totalScreened: number,
    results: ScanStockEntry[],
    opts?: { tags?: string[]; notes?: string },
  ): Promise<string> {
    const release = await this.writeMutex.acquire();
    try {
      const id = generateScanId();
      const now = new Date();
      const record: ScanRecord = {
        id,
        createdAt: now.toISOString(),
        date: now.toISOString().slice(0, 10),
        screenerId,
        universe,
        market,
        totalScreened,
        resultCount: results.length,
        results,
        tags: opts?.tags ?? [],
        notes: opts?.notes,
      };

      // Persist full record
      this.writeRecord(record);

      // Update index
      const entry = this.toIndexEntry(record);
      this.index.push(entry);

      // Prune old entries beyond maxResults
      if (this.index.length > this.maxResults) {
        // Sort oldest first, remove oldest
        this.index.sort(
          (a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime(),
        );
        const toRemove = this.index.splice(0, this.index.length - this.maxResults);
        for (const r of toRemove) this.deleteRecordFile(r.id);
      }

      this.saveIndex();
      return id;
    } finally {
      release();
    }
  }

  /** Delete a scan record. */
  async delete(id: string): Promise<boolean> {
    const release = await this.writeMutex.acquire();
    try {
      const idx = this.index.findIndex((e) => e.id === id);
      if (idx < 0) return false;
      this.index.splice(idx, 1);
      this.deleteRecordFile(id);
      this.saveIndex();
      return true;
    } finally {
      release();
    }
  }

  // ── Read operations ───────────────────────────────────────────

  /** Query index with filters. Single-pass filter. */
  query(q: ScanQuery = {}): ScanIndexEntry[] {
    const afterTs = q.after ? new Date(q.after).getTime() : 0;
    const beforeTs = q.before ? new Date(q.before).getTime() : Infinity;

    const results = this.index.filter((e) => {
      if (q.screenerId && e.screenerId !== q.screenerId) return false;
      if (q.universe && e.universe !== q.universe) return false;
      if (q.market && e.market !== q.market) return false;
      if (q.date && e.date !== q.date) return false;
      if (q.tag && !e.tags.includes(q.tag)) return false;
      const ts = new Date(e.createdAt).getTime();
      if (ts < afterTs || ts > beforeTs) return false;
      return true;
    });

    // Sort
    const sortBy = q.sortBy ?? "createdAt";
    const mult = (q.sortDir ?? "desc") === "desc" ? -1 : 1;
    results.sort((a, b) => {
      if (sortBy === "createdAt") {
        return mult * (new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime());
      }
      return mult * (a.resultCount - b.resultCount);
    });

    // Pagination
    const offset = q.offset ?? 0;
    const limit = q.limit ?? 50;
    return results.slice(offset, offset + limit);
  }

  /** Get full scan record by id. */
  getFullResult(id: string): ScanRecord | null {
    if (!this.dataDir) return null;
    const filePath = join(this.dataDir, `${id}.json`);
    if (!existsSync(filePath)) return null;
    try {
      return JSON.parse(readFileSync(filePath, "utf-8")) as ScanRecord;
    } catch {
      return null;
    }
  }

  /** Get lightweight index entry by id. */
  getEntry(id: string): ScanIndexEntry | undefined {
    return this.index.find((e) => e.id === id);
  }

  /** Track stock appearance frequency across scans within a date range. */
  getStockFrequency(opts?: {
    screenerId?: string;
    after?: string;
    before?: string;
    minAppearances?: number;
    limit?: number;
  }): StockFrequency[] {
    // Get matching scans in chronological order so latestScore is correct
    const scans = this.query({
      screenerId: opts?.screenerId,
      after: opts?.after,
      before: opts?.before,
      sortDir: "asc",
      limit: 1000,
    });

    // Load full results and count appearances
    const freq = new Map<
      string,
      { name?: string; count: number; dates: string[]; scores: number[] }
    >();
    for (const scan of scans) {
      const full = this.getFullResult(scan.id);
      if (!full) continue;
      for (const stock of full.results) {
        const entry = freq.get(stock.code);
        if (entry) {
          entry.count++;
          entry.dates.push(scan.date);
          if (stock.score != null) entry.scores.push(stock.score);
          if (stock.name && !entry.name) entry.name = stock.name;
        } else {
          freq.set(stock.code, {
            name: stock.name,
            count: 1,
            dates: [scan.date],
            scores: stock.score != null ? [stock.score] : [],
          });
        }
      }
    }

    // Build result
    const minApp = opts?.minAppearances ?? 1;
    const result: StockFrequency[] = [];
    for (const [code, data] of freq) {
      if (data.count < minApp) continue;
      const avgScore =
        data.scores.length > 0
          ? data.scores.reduce((a, b) => a + b, 0) / data.scores.length
          : undefined;
      result.push({
        code,
        name: data.name,
        appearances: data.count,
        dates: [...new Set(data.dates)].sort(),
        avgScore,
        latestScore: data.scores.length > 0 ? data.scores[data.scores.length - 1] : undefined,
      });
    }

    result.sort((a, b) => b.appearances - a.appearances);
    return result.slice(0, opts?.limit ?? 50);
  }

  /** Get the latest two scan entries for a given screener (for auto-compare). */
  getLatestPair(screenerId?: string): { baseId: string; compareId: string } | null {
    const entries = this.query({
      screenerId,
      sortBy: "createdAt",
      sortDir: "desc",
      limit: 2,
    });
    if (entries.length < 2) return null;
    // entries[0] is newer (compare), entries[1] is older (base)
    return { baseId: entries[1].id, compareId: entries[0].id };
  }

  /** Compare two scan runs — which stocks added/removed/changed score. */
  compare(baseId: string, compareId: string): ScanComparison | null {
    const base = this.getFullResult(baseId);
    const compare = this.getFullResult(compareId);
    if (!base || !compare) return null;

    const baseMap = new Map(base.results.map((s) => [s.code, s]));
    const compareMap = new Map(compare.results.map((s) => [s.code, s]));

    const overlap: ScanComparison["overlap"] = [];
    const removed: ScanStockEntry[] = [];
    const added: ScanStockEntry[] = [];

    for (const [code, s] of baseMap) {
      const c = compareMap.get(code);
      if (c) {
        overlap.push({
          code,
          name: s.name ?? c.name,
          baseScore: s.score,
          compareScore: c.score,
          scoreDelta: s.score != null && c.score != null ? c.score - s.score : undefined,
        });
      } else {
        removed.push(s);
      }
    }
    for (const [code, s] of compareMap) {
      if (!baseMap.has(code)) added.push(s);
    }

    return {
      baseId,
      compareId,
      baseDate: base.date,
      compareDate: compare.date,
      screenerId: base.screenerId,
      overlap,
      removed,
      added,
      overlapCount: overlap.length,
      removedCount: removed.length,
      addedCount: added.length,
    };
  }

  // ── Private ───────────────────────────────────────────────────

  private ensureDir(): void {
    if (this.dataDir && !existsSync(this.dataDir)) {
      mkdirSync(this.dataDir, { recursive: true });
    }
  }

  private loadIndex(): void {
    if (!this.dataDir) return;
    const indexPath = join(this.dataDir, "_index.json");
    if (!existsSync(indexPath)) {
      // Rebuild index from individual record files
      this.rebuildIndex();
      return;
    }
    try {
      this.index = JSON.parse(readFileSync(indexPath, "utf-8")) as ScanIndexEntry[];
    } catch {
      this.rebuildIndex();
    }
  }

  private rebuildIndex(): void {
    if (!this.dataDir) return;
    const files = readdirSync(this.dataDir).filter(
      (f) => f.startsWith("scan_") && f.endsWith(".json"),
    );
    this.index = [];
    for (const file of files) {
      try {
        const record = JSON.parse(readFileSync(join(this.dataDir, file), "utf-8")) as ScanRecord;
        this.index.push(this.toIndexEntry(record));
      } catch {
        // Skip corrupt files
      }
    }
    this.index.sort((a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime());
    this.saveIndex();
  }

  private saveIndex(): void {
    if (!this.dataDir) return;
    writeFileSync(join(this.dataDir, "_index.json"), JSON.stringify(this.index, null, 2));
  }

  private writeRecord(record: ScanRecord): void {
    if (!this.dataDir) return;
    writeFileSync(join(this.dataDir, `${record.id}.json`), JSON.stringify(record, null, 2));
  }

  private deleteRecordFile(id: string): void {
    if (!this.dataDir) return;
    const filePath = join(this.dataDir, `${id}.json`);
    try {
      unlinkSync(filePath);
    } catch {
      // best-effort
    }
  }

  private toIndexEntry(record: ScanRecord): ScanIndexEntry {
    return {
      id: record.id,
      createdAt: record.createdAt,
      date: record.date,
      screenerId: record.screenerId,
      universe: record.universe,
      market: record.market,
      totalScreened: record.totalScreened,
      resultCount: record.resultCount,
      topCodes: record.results.slice(0, 10).map((r) => r.code),
      tags: record.tags,
      notes: record.notes,
    };
  }
}
