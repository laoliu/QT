export type BacktestRequest = {
  strategyId: string;
  symbols: string[];
  startDate: string; // YYYY-MM-DD
  endDate: string;
  initialCash: number;
  /** Market type override — when set, engine uses this instead of auto-detecting from symbol */
  market?: MarketType;
  /**
   * K-line interval (default: "1d" daily bars).
   * Use "5m"/"15m"/"30m"/"60m" for intraday strategies.
   * Note: intraday data requires xtquant (QMT) or a compatible provider.
   */
  interval?: KlineInterval;
  /**
   * A-share fee defaults (realistic for mainland China retail accounts):
   *   commission    = 0.0003  (万3, both sides; floor minCommission)
   *   stampDuty     = 0.0005  (0.05%, sell side only, post-2023-08 rate)
   *   transferFee   = 0.00002 (0.002%, both sides; SSE stocks)
   *   slippage      = 0.001   (0.1%, models market impact on daily bars)
   *   minCommission = 5       (¥5 minimum per leg)
   */
  commission?: number;
  stampDuty?: number;
  transferFee?: number;
  minCommission?: number;
  slippage?: number;
  parameters?: Record<string, unknown>;
  engine?: BacktestEngine;
  benchmark?: string; // e.g. "000300" for CSI 300
};

