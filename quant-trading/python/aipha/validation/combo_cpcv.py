"""组合层 CPCV/WF 验证框架 — ComboCPCV。

针对多组件 NAV 加权组合执行时间序列 Walk-Forward 验证：
- 输入：多组件 NAV 序列 + 固定权重（或权重网格）
- 流程：Purged K-Fold 分折 → 每折计算 IS/OOS 组合 SR
- 输出：组合 WF Score、IS→OOS 衰减、PBO、逐折明细

与单策略 WF 的区别：
- 单策略 WF 验证模型预测能力（train_fn → eval_fn）
- 组合 CPCV 验证权重配置在不同制度下的稳健性

验收标准 (§1.4 原则C/E):
- IS→OOS Sharpe 衰减 ≤ 50%
- PBO < 0.50
- WF Score ≥ 5.0（平均 OOS SR × 折数占比）

Usage::

    cpcv = ComboCPCV(n_folds=5, purge_days=5)
    result = cpcv.validate(
        nav_dict={"ml": ml_nav, "cb": cb_nav, "etf": etf_nav},
        weights={"ml": 0.38, "cb": 0.15, "etf": 0.35},
    )
    print(f"PBO={result.pbo:.3f}, Degradation={result.degradation:.1%}")
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any, Optional

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

TRADING_DAYS_PER_YEAR = 244


@dataclass
class ComboFoldResult:
    """单折组合 WF 结果。"""
    fold_id: int
    is_start: str
    is_end: str
    oos_start: str
    oos_end: str
    is_sr: float
    oos_sr: float
    is_ar: float
    oos_ar: float
    is_mdd: float
    oos_mdd: float
    degradation: float  # 1 - oos_sr / is_sr


@dataclass
class ComboCPCVResult:
    """组合 CPCV 验证汇总结果。"""
    profile_name: str
    n_folds: int
    fold_results: list[ComboFoldResult]
    avg_is_sr: float
    avg_oos_sr: float
    degradation: float       # 1 - avg_oos_sr / avg_is_sr
    pbo: float               # 简化 PBO: OOS 亏损折数 / 总折数
    wf_score: float          # avg_oos_sr × (盈利折数/总折数) × 10
    cv_oos_returns: float    # OOS 年化收益的 CV (变异系数)
    passed: bool             # 是否通过全部门禁
    gate_details: dict[str, bool] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """序列化。"""
        return {
            "profile_name": self.profile_name,
            "n_folds": self.n_folds,
            "avg_is_sr": self.avg_is_sr,
            "avg_oos_sr": self.avg_oos_sr,
            "degradation": self.degradation,
            "pbo": self.pbo,
            "wf_score": self.wf_score,
            "cv_oos_returns": self.cv_oos_returns,
            "passed": self.passed,
            "gate_details": self.gate_details,
            "folds": [
                {
                    "fold": fr.fold_id,
                    "is_period": f"{fr.is_start} ~ {fr.is_end}",
                    "oos_period": f"{fr.oos_start} ~ {fr.oos_end}",
                    "is_sr": fr.is_sr,
                    "oos_sr": fr.oos_sr,
                    "oos_ar": fr.oos_ar,
                    "degradation": fr.degradation,
                }
                for fr in self.fold_results
            ],
        }

    def to_markdown(self) -> str:
        """Markdown 报告输出。"""
        icon = "✅" if self.passed else "❌"
        lines = [
            f"# 组合 CPCV 验证报告 — {self.profile_name}",
            f"",
            f"**判定**: {icon} {'PASS' if self.passed else 'FAIL'}",
            f"",
            f"## 汇总指标",
            f"",
            f"| 指标 | 值 | 门槛 | 判定 |",
            f"|------|-----|------|------|",
            f"| IS→OOS 衰减 | {self.degradation:.1%} | ≤ 50% | {'✅' if self.gate_details.get('degradation_le_50pct') else '❌'} |",
            f"| PBO | {self.pbo:.3f} | < 0.50 | {'✅' if self.gate_details.get('pbo_lt_050') else '❌'} |",
            f"| WF Score | {self.wf_score:.2f} | ≥ 5.0 | {'✅' if self.gate_details.get('wf_score_ge_5') else '❌'} |",
            f"| OOS AR CV | {self.cv_oos_returns:.2f} | ≤ 2.0 | {'✅' if self.gate_details.get('cv_le_2') else '❌'} |",
            f"| Avg IS SR | {self.avg_is_sr:.3f} | — | — |",
            f"| Avg OOS SR | {self.avg_oos_sr:.3f} | — | — |",
            f"",
            f"## 逐折明细",
            f"",
            f"| Fold | IS Period | OOS Period | IS SR | OOS SR | OOS AR | 衰减 |",
            f"|------|-----------|------------|-------|--------|--------|------|",
        ]
        for fr in self.fold_results:
            lines.append(
                f"| {fr.fold_id} | {fr.is_start}~{fr.is_end} | "
                f"{fr.oos_start}~{fr.oos_end} | {fr.is_sr:.3f} | "
                f"{fr.oos_sr:.3f} | {fr.oos_ar:.1%} | {fr.degradation:.1%} |"
            )
        lines.append("")
        lines.append("---")
        lines.append("*Generated by ComboCPCV*")
        return "\n".join(lines)


class ComboCPCV:
    """组合层 CPCV 验证器。"""

    def __init__(
        self,
        n_folds: int = 5,
        purge_days: int = 5,
        mode: str = "rolling",
        min_fold_days: int = 120,
    ) -> None:
        """初始化。

        Args:
            n_folds: 折数 (默认 5)
            purge_days: 训练/测试间净化天数
            mode: "rolling" (固定窗口) 或 "expanding" (扩展窗口)
            min_fold_days: 每折最小天数
        """
        self._n_folds = n_folds
        self._purge_days = purge_days
        self._mode = mode
        self._min_fold_days = min_fold_days

    def validate(
        self,
        nav_dict: dict[str, pd.Series],
        weights: dict[str, float],
        profile_name: str = "unnamed",
    ) -> ComboCPCVResult:
        """执行组合 CPCV 验证。

        Args:
            nav_dict: 组件名→NAV序列 (DatetimeIndex)
            weights: 组件名→权重
            profile_name: 组合名称

        Returns:
            ComboCPCVResult 包含逐折明细和汇总判定
        """
        # 对齐收益率
        aligned_rets = self._align_nav_returns(nav_dict)
        total_days = len(aligned_rets)
        dates = aligned_rets.index

        # 生成折叠
        folds = self._generate_folds(total_days)
        if len(folds) < 2:
            raise ValueError(
                f"数据不足: {total_days} 天无法生成 ≥2 折 "
                f"(需要至少 {self._min_fold_days * 4} 天)"
            )

        # 计算组合日收益序列
        w_arr = np.array([weights.get(col, 0) for col in aligned_rets.columns])
        w_arr = w_arr / w_arr.sum()  # 归一化
        combo_rets = (aligned_rets.values @ w_arr)
        combo_ret_series = pd.Series(combo_rets, index=dates)

        # 逐折计算
        fold_results: list[ComboFoldResult] = []
        for fold_id, (tr_s, tr_e, te_s, te_e) in enumerate(folds):
            is_rets = combo_ret_series.iloc[tr_s:tr_e]
            oos_rets = combo_ret_series.iloc[te_s:te_e]

            is_metrics = self._compute_combo_metrics(is_rets)
            oos_metrics = self._compute_combo_metrics(oos_rets)

            is_sr = is_metrics["sr"]
            oos_sr = oos_metrics["sr"]
            deg = 1 - (oos_sr / is_sr) if abs(is_sr) > 1e-8 else 0.0

            fold_results.append(ComboFoldResult(
                fold_id=fold_id,
                is_start=str(dates[tr_s].date()),
                is_end=str(dates[min(tr_e - 1, total_days - 1)].date()),
                oos_start=str(dates[te_s].date()),
                oos_end=str(dates[min(te_e - 1, total_days - 1)].date()),
                is_sr=round(is_sr, 3),
                oos_sr=round(oos_sr, 3),
                is_ar=round(is_metrics["ar"], 4),
                oos_ar=round(oos_metrics["ar"], 4),
                is_mdd=round(is_metrics["mdd"], 4),
                oos_mdd=round(oos_metrics["mdd"], 4),
                degradation=round(deg, 3),
            ))

        # 汇总
        avg_is_sr = float(np.mean([fr.is_sr for fr in fold_results]))
        avg_oos_sr = float(np.mean([fr.oos_sr for fr in fold_results]))
        degradation = 1 - (avg_oos_sr / avg_is_sr) if abs(avg_is_sr) > 1e-8 else 0.0
        pbo = self._compute_pbo(fold_results)
        wf_score = self._compute_wf_score(fold_results)

        # OOS 年化收益 CV
        oos_ars = [fr.oos_ar for fr in fold_results]
        mean_oos_ar = np.mean(oos_ars)
        std_oos_ar = np.std(oos_ars)
        cv = float(std_oos_ar / abs(mean_oos_ar)) if abs(mean_oos_ar) > 1e-8 else 99.0

        # 门禁判定
        gate_details = {
            "degradation_le_50pct": degradation <= 0.50,
            "pbo_lt_050": pbo < 0.50,
            "wf_score_ge_5": wf_score >= 5.0,
            "cv_le_2": cv <= 2.0,
        }
        passed = all(gate_details.values())

        return ComboCPCVResult(
            profile_name=profile_name,
            n_folds=len(fold_results),
            fold_results=fold_results,
            avg_is_sr=round(avg_is_sr, 3),
            avg_oos_sr=round(avg_oos_sr, 3),
            degradation=round(degradation, 3),
            pbo=round(pbo, 3),
            wf_score=round(wf_score, 3),
            cv_oos_returns=round(cv, 3),
            passed=passed,
            gate_details=gate_details,
        )

    def _align_nav_returns(
        self,
        nav_dict: dict[str, pd.Series],
    ) -> pd.DataFrame:
        """对齐多组件收益率序列。

        Returns:
            DataFrame，列名为组件名，值为日收益率，DatetimeIndex
        """
        rets_dict = {}
        for name, nav in nav_dict.items():
            nav_sorted = nav.sort_index()
            ret = nav_sorted.pct_change().dropna()
            rets_dict[name] = ret

        aligned = pd.DataFrame(rets_dict).dropna()
        if aligned.empty:
            raise ValueError("组件 NAV 对齐后无有效数据")
        return aligned

    def _compute_combo_metrics(
        self,
        returns: pd.Series,
    ) -> dict[str, float]:
        """计算组合指标 (SR/AR/MDD)。

        Args:
            returns: 日收益率序列

        Returns:
            {"sr": float, "ar": float, "mdd": float}
        """
        if len(returns) < 10:
            return {"sr": 0.0, "ar": 0.0, "mdd": 0.0}

        ann_factor = np.sqrt(TRADING_DAYS_PER_YEAR)
        mean_r = returns.mean()
        std_r = returns.std()
        sr = float(mean_r / std_r * ann_factor) if std_r > 1e-12 else 0.0

        # 年化收益
        total_ret = (1 + returns).prod() - 1
        n_years = len(returns) / TRADING_DAYS_PER_YEAR
        ar = float((1 + total_ret) ** (1 / max(n_years, 0.01)) - 1)

        # 最大回撤
        cum = (1 + returns).cumprod()
        peak = cum.cummax()
        dd = (cum - peak) / peak
        mdd = float(-dd.min())

        return {"sr": sr, "ar": ar, "mdd": mdd}

    def _generate_folds(
        self,
        total_days: int,
    ) -> list[tuple[int, int, int, int]]:
        """生成 Walk-Forward 折叠。

        Returns:
            [(train_start, train_end, test_start, test_end), ...]
        """
        # 计算每折 OOS 大小
        test_size = total_days // (self._n_folds + 1)
        test_size = max(test_size, self._min_fold_days)

        # IS 窗口大小（rolling 模式）
        if self._mode == "rolling":
            train_size = test_size * 3  # IS = 3× OOS
        else:
            train_size = 0  # expanding: 从头开始

        folds = []
        for i in range(self._n_folds):
            test_start = total_days - (self._n_folds - i) * test_size
            test_end = test_start + test_size

            if test_start < 0 or test_end > total_days:
                continue

            train_end = test_start - self._purge_days

            if self._mode == "expanding":
                train_start = 0
            else:
                train_start = max(0, train_end - train_size)

            if train_end - train_start < self._min_fold_days:
                continue

            folds.append((train_start, train_end, test_start, min(test_end, total_days)))

        return folds

    def _compute_pbo(
        self,
        fold_results: list[ComboFoldResult],
    ) -> float:
        """计算简化 PBO: OOS SR < 0 的折数 / 总折数。

        严格 PBO (Bailey 2014) 需要多策略排列组合检验。
        对于固定权重组合，使用简化版：OOS 亏损占比。
        """
        if not fold_results:
            return 0.0
        n_negative = sum(1 for fr in fold_results if fr.oos_sr <= 0)
        return n_negative / len(fold_results)

    def _compute_wf_score(
        self,
        fold_results: list[ComboFoldResult],
    ) -> float:
        """计算 WF Score: avg_oos_sr × (盈利折数/总折数) × 10。"""
        if not fold_results:
            return 0.0
        oos_srs = [fr.oos_sr for fr in fold_results]
        avg_oos_sr = np.mean(oos_srs)
        n_profitable = sum(1 for sr in oos_srs if sr > 0)
        profit_ratio = n_profitable / len(fold_results)
        return float(avg_oos_sr * profit_ratio * 10)
